// ---------------------------------------------------------------------------
// OAuth URL
// ---------------------------------------------------------------------------

/**
 * Build the GitHub OAuth authorization URL with `read:user` and `user:email` scopes.
 *
 * @param clientId - GitHub OAuth App client ID
 * @param redirectUri - Callback URL GitHub redirects to after authorization
 * @param state - CSRF state token (generated by {@link createStateCookie})
 * @returns Fully qualified GitHub authorization URL with query parameters
 */
export function buildAuthUrl(clientId: string, redirectUri: string, state: string): string {
  const params = new URLSearchParams({
    client_id: clientId,
    redirect_uri: redirectUri,
    scope: "read:user user:email",
    state,
  });
  return `https://github.com/login/oauth/authorize?${params.toString()}`;
}

// ---------------------------------------------------------------------------
// CSRF state cookie
// ---------------------------------------------------------------------------

const STATE_COOKIE_NAME = "chapa_oauth_state";

function cookieFlags(): string {
  return buildAuthCookieFlags(getBaseUrl());
}

/**
 * Generate a cryptographically random CSRF state token and return it as a
 * `Set-Cookie` header value (HttpOnly, SameSite=Lax, 10-minute Max-Age).
 *
 * @returns Object with `state` (hex token) and `cookie` (Set-Cookie header value)
 */
export function createStateCookie(): { state: string; cookie: string } {
  const state = randomBytes(16).toString("hex");
  const cookie = `${STATE_COOKIE_NAME}=${state}; ${cookieFlags()}; Max-Age=600`;
  return { state, cookie };
}

/**
 * Validate the OAuth CSRF state parameter against the value stored in the
 * `chapa_oauth_state` cookie.
 *
 * Uses `crypto.timingSafeEqual` for constant-time comparison to prevent
 * timing-based side-channel attacks on the state token. Both buffers are
 * compared only when their lengths match; a length mismatch returns `false`
 * immediately (safe because length is not secret).
 *
 * @param cookieHeader - Raw `Cookie` header string from the incoming request.
 *   The state cookie is extracted by name from this semicolon-delimited string.
 * @param queryState - The `state` query parameter returned by GitHub's OAuth
 *   redirect. Must match the cookie value exactly.
 * @returns `true` if both values are present and identical; `false` otherwise.
 *
 * @example
 * ```ts
 * const isValid = validateState(
 *   request.headers.get("cookie"),
 *   url.searchParams.get("state"),
 * );
 * if (!isValid) return new Response("CSRF validation failed", { status: 403 });
 * ```
 */
export function validateState(
  cookieHeader: string | null,
  queryState: string | null,
): boolean {
  if (!cookieHeader || !queryState) return false;
  const match = cookieHeader
    .split(";")
    .map((c) => c.trim())
    .find((c) => c.startsWith(`${STATE_COOKIE_NAME}=`));
  if (!match) return false;
  const cookieState = match.slice(STATE_COOKIE_NAME.length + 1);
  const cookieBuf = Buffer.from(cookieState, "utf8");
  const queryBuf = Buffer.from(queryState, "utf8");
  if (cookieBuf.length !== queryBuf.length) return false;
  return timingSafeEqual(cookieBuf, queryBuf);
}

/**
 * Return a `Set-Cookie` header value that immediately expires the CSRF state cookie.
 *
 * @returns Set-Cookie header string with Max-Age=0
 */
export function clearStateCookie(): string {
  return `${STATE_COOKIE_NAME}=; ${cookieFlags()}; Max-Age=0`;
}

